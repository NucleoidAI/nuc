import { readFileSync } from "node:fs";
import { relative, resolve, sep } from "node:path";
import {
  type CodeLocation,
  type Finding,
  type MessagePart,
  type Region,
  type Report,
  type Severity,
  SEVERITIES,
} from "./sarif";

export type ReportMeta = {
  project: string;
  generatedAt: Date;
  branch: string | null;
  commit: string | null;
  suite: string;
  sarifPath: string;
};

type SourceReader = (file: string) => string[] | null;

const SNIPPET_CONTEXT_LINES = 3;

const SEVERITY_LABELS: Record<Severity, string> = {
  critical: "Critical",
  high: "High",
  medium: "Medium",
  low: "Low",
};

const HTML_ESCAPES: Record<string, string> = {
  "&": "&amp;",
  "<": "&lt;",
  ">": "&gt;",
  '"': "&quot;",
  "'": "&#39;",
};

export function renderReport({
  report,
  sourceRoot,
  meta,
}: {
  report: Report;
  sourceRoot: string;
  meta: ReportMeta;
}): string {
  const readSource = createSourceReader(sourceRoot);
  const findings = report.findings
    .map((finding, index) => renderFinding({ finding, index, readSource }))
    .join("");

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(meta.project)} Security Report</title>
<style>${STYLES}</style>
</head>
<body>
<main>
${renderHeader({ report, meta })}
${renderSummary(report)}
${renderToolbar(report)}
<section class="findings" aria-label="Findings">
${findings}
<p class="empty" id="no-match"${report.findings.length === 0 ? "" : " hidden"}>${
    report.findings.length === 0 ? "No findings. CodeQL reported nothing for this scan." : "No findings match the current filter."
  }</p>
</section>
<footer class="page-foot">Generated by <code>scripts/security-report</code> from <code>${escapeHtml(
    displayPath({ root: sourceRoot, path: meta.sarifPath })
  )}</code></footer>
</main>
<script>${CLIENT_SCRIPT}</script>
</body>
</html>
`;
}

function renderHeader({ report, meta }: { report: Report; meta: ReportMeta }): string {
  const facts: [string, string | null][] = [
    ["Generated", formatDate(meta.generatedAt)],
    ["Branch", meta.branch],
    ["Commit", meta.commit],
    ["Scanner", report.version ? `${report.tool} ${report.version}` : report.tool],
    ["Query suite", meta.suite],
    ["Files scanned", report.filesScanned === null ? null : formatNumber(report.filesScanned)],
    ["Lines of code", report.linesOfCode === null ? null : formatNumber(report.linesOfCode)],
  ];
  const rows = facts
    .filter((fact): fact is [string, string] => fact[1] !== null)
    .map(([label, value]) => `<div><dt>${escapeHtml(label)}</dt><dd>${escapeHtml(value)}</dd></div>`)
    .join("");

  return `<header class="page-head">
<p class="eyebrow">Static analysis</p>
<h1>${escapeHtml(meta.project)} Security Report</h1>
<dl class="facts">${rows}</dl>
</header>`;
}

function renderSummary(report: Report): string {
  const counts = countBySeverity(report.findings);
  const cards = SEVERITIES.map(
    (severity) => `<button class="card sev-${severity}" type="button" data-filter="${severity}">
<span class="card-label"><span class="dot"></span>${SEVERITY_LABELS[severity]}</span>
<span class="card-value">${counts[severity]}</span>
</button>`
  ).join("");

  return `<section class="summary" aria-label="Summary">
<button class="card card-total" type="button" data-filter="all">
<span class="card-label">Total findings</span>
<span class="card-value">${report.findings.length}</span>
</button>
${cards}
</section>
<p class="legend">Severity is CodeQL's security-severity score (0–10): Critical ≥ 9.0, High ≥ 7.0, Medium ≥ 4.0, Low below. The label on the right of each finding is the rule's level (error, warning, note).</p>`;
}

function renderToolbar(report: Report): string {
  if (report.findings.length === 0) return "";

  return `<div class="toolbar">
<p class="filter-state" id="filter-state">Showing all ${report.findings.length} findings</p>
<input id="search" type="search" placeholder="Filter by file, rule or CWE" aria-label="Filter findings">
</div>`;
}

function renderFinding({
  finding,
  index,
  readSource,
}: {
  finding: Finding;
  index: number;
  readSource: SourceReader;
}): string {
  const anchor = `finding-${index + 1}`;
  const searchText = [
    finding.title,
    finding.ruleId,
    finding.location.file,
    ...finding.cwes.map((cwe) => `cwe-${cwe}`),
  ]
    .join(" ")
    .toLowerCase();

  return `<article class="finding sev-${finding.severity}" id="${anchor}" data-severity="${finding.severity}" data-search="${escapeHtml(searchText)}">
<header class="finding-head">
<span class="badge" title="CodeQL security-severity score (0–10)">${SEVERITY_LABELS[finding.severity]}${finding.score === null ? "" : ` <b>${finding.score.toFixed(1)}</b>`}</span>
<h2><a href="#${anchor}">${escapeHtml(finding.title)}</a></h2>
<span class="level">${escapeHtml(finding.level)}</span>
</header>
<p class="where"><code>${escapeHtml(formatLocation(finding.location))}</code></p>
<p class="message">${renderMessage(finding.message)}</p>
${renderSnippet({ location: finding.location, readSource, context: SNIPPET_CONTEXT_LINES })}
${renderFlow({ finding, readSource })}
${renderRuleDetails(finding)}
</article>`;
}

function renderMessage(parts: MessagePart[]): string {
  return parts
    .map((part) => {
      if (!part.reference) return escapeHtml(part.text);

      return `<span class="ref">${escapeHtml(part.text)}</span> <code class="ref-at">${escapeHtml(
        formatLocation(part.reference)
      )}</code>`;
    })
    .join("");
}

function renderRuleDetails(finding: Finding): string {
  const cwes = finding.cwes
    .map(
      (cwe) =>
        `<a class="tag" href="https://cwe.mitre.org/data/definitions/${cwe}.html" target="_blank" rel="noreferrer">CWE-${cwe}</a>`
    )
    .join("");
  const precision = finding.precision
    ? `<span class="tag tag-muted">precision: ${escapeHtml(finding.precision)}</span>`
    : "";

  return `<footer class="rule">
${finding.description ? `<p>${escapeHtml(finding.description)}</p>` : ""}
<div class="tags"><code class="rule-id">${escapeHtml(finding.ruleId)}</code>${cwes}${precision}</div>
</footer>`;
}

function renderFlow({ finding, readSource }: { finding: Finding; readSource: SourceReader }): string {
  if (finding.flow.length < 2) return "";

  const steps = finding.flow
    .map((step, index) => {
      const role = flowRole({ index, total: finding.flow.length });

      return `<li>
<div class="step-head"><span class="step-role">${role}</span><code>${escapeHtml(
        formatLocation(step)
      )}</code>${step.message ? `<span class="step-note">${escapeHtml(step.message)}</span>` : ""}</div>
${renderSnippet({ location: step, readSource, context: 0 })}
</li>`;
    })
    .join("");
  const extra =
    finding.extraPaths > 0
      ? ` <span class="muted">+${finding.extraPaths} more path${finding.extraPaths === 1 ? "" : "s"}</span>`
      : "";

  return `<details class="flow">
<summary>Data flow <span class="muted">${finding.flow.length} steps</span>${extra}</summary>
<ol>${steps}</ol>
</details>`;
}

function flowRole({ index, total }: { index: number; total: number }): string {
  if (index === 0) return "Source";
  if (index === total - 1) return "Sink";
  return `Step ${index + 1}`;
}

function renderSnippet({
  location,
  readSource,
  context,
}: {
  location: CodeLocation;
  readSource: SourceReader;
  context: number;
}): string {
  const lines = readSource(location.file);

  if (!lines) return `<p class="muted no-source">Source not available for ${escapeHtml(location.file)}</p>`;

  const { region } = location;
  const first = Math.max(region.startLine - context, 1);
  const last = Math.min((region.endLine ?? region.startLine) + context, lines.length);
  const rows = lines
    .slice(first - 1, last)
    .map((text, offset) => renderSourceLine({ text, lineNumber: first + offset, region }))
    .join("");

  return `<pre class="code"><code>${rows}</code></pre>`;
}

function renderSourceLine({
  text,
  lineNumber,
  region,
}: {
  text: string;
  lineNumber: number;
  region: Region;
}): string {
  const firstLine = region.startLine;
  const lastLine = region.endLine ?? firstLine;
  const gutter = `<span class="ln">${lineNumber}</span>`;

  if (lineNumber < firstLine || lineNumber > lastLine) {
    return `<span class="line">${gutter}${escapeHtml(text)}</span>`;
  }

  const from = lineNumber === firstLine ? (region.startColumn ?? 1) - 1 : 0;
  const to =
    lineNumber === lastLine && region.endColumn !== undefined ? region.endColumn - 1 : text.length;

  return `<span class="line marked">${gutter}${escapeHtml(text.slice(0, from))}<mark>${escapeHtml(
    text.slice(from, to)
  )}</mark>${escapeHtml(text.slice(to))}</span>`;
}

function createSourceReader(sourceRoot: string): SourceReader {
  const root = resolve(sourceRoot);
  const cache = new Map<string, string[] | null>();

  return function readSource(file: string): string[] | null {
    const cached = cache.get(file);

    if (cached !== undefined) return cached;

    const lines = readLines({ root, file });
    cache.set(file, lines);

    return lines;
  };
}

function readLines({ root, file }: { root: string; file: string }): string[] | null {
  const path = resolve(root, file);

  if (!path.startsWith(`${root}${sep}`)) return null;

  try {
    return readFileSync(path, "utf8").split(/\r?\n/);
  } catch (error: unknown) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") return null;
    throw new Error(`Could not read ${file} for the report`, { cause: error });
  }
}

function countBySeverity(findings: Finding[]): Record<Severity, number> {
  return Object.fromEntries(
    SEVERITIES.map((severity) => [
      severity,
      findings.filter((finding) => finding.severity === severity).length,
    ])
  ) as Record<Severity, number>;
}

function formatLocation(location: CodeLocation): string {
  const { startLine, startColumn } = location.region;
  return startColumn === undefined
    ? `${location.file}:${startLine}`
    : `${location.file}:${startLine}:${startColumn}`;
}

function displayPath({ root, path }: { root: string; path: string }): string {
  const fromRoot = relative(root, path);
  return fromRoot.startsWith("..") ? path : fromRoot;
}

function formatDate(date: Date): string {
  return date.toLocaleString("en-GB", { dateStyle: "medium", timeStyle: "short" });
}

function formatNumber(value: number): string {
  return value.toLocaleString("en-US");
}

function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, (character) => HTML_ESCAPES[character] ?? character);
}

