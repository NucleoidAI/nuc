export type ReportVariant = "screen" | "print";

export type ReportMeta = {
  project: string;
  generatedAt: Date;
  branch: string | null;
  commit: string | null;
  suite: string;
  sarifPath: string;
};

type SourceReader = (file: string) => string[] | null;

type NumberedFinding = { finding: Finding; number: string; anchor: string; searchText: string };

const SNIPPET_CONTEXT_LINES = 3;

const SEVERITY_LABELS: Record<Severity, string> = {
  critical: "Critical",
  high: "High",
  medium: "Medium",
  low: "Low",
};

const HTML_ESCAPES: Record<string, string> = {
  "&": "&amp;",
  "<": "&lt;",
  ">": "&gt;",
  '"': "&quot;",
  "'": "&#39;",
};

const FONT_STYLESHEET =
  "https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500&family=IBM+Plex+Sans:ital,wght@0,400;0,500;0,600;1,400&display=swap";

export function renderReport({
  report,
  sourceRoot,
  meta,
  variant = "screen",
}: {
  report: Report;
  sourceRoot: string;
  meta: ReportMeta;
  variant?: ReportVariant;
}): string {
  const isPrint = variant === "print";
  const readSource = createSourceReader(sourceRoot);
  const numbered = report.findings.map((finding, index) => numberFinding({ finding, index }));
  const hasFindings = numbered.length > 0;

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(meta.project)} — Security report</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="${FONT_STYLESHEET}">
<style>${STYLES}</style>
</head>
<body>
<main class="page">
${renderMasthead({ report, meta })}
${renderSummary(report)}
${hasFindings ? renderIndex(numbered) : renderEmpty()}
${hasFindings ? renderDetails({ numbered, readSource, isPrint }) : ""}
<footer class="colophon">
<p>Generated by <code>bun run security:report</code> from <code>${escapeHtml(
    displayPath({ root: sourceRoot, path: meta.sarifPath })
  )}</code>. Line numbers refer to the working tree at the time of the report.</p>
</footer>
</main>
${isPrint ? "" : `<script>${CLIENT_SCRIPT}</script>`}
</body>
</html>
`;
}

function numberFinding({ finding, index }: { finding: Finding; index: number }): NumberedFinding {
  const number = String(index + 1).padStart(2, "0");

  return {
    finding,
    number,
    anchor: `finding-${number}`,
    searchText: [finding.title, finding.ruleId, finding.location.file, ...finding.cwes.map((cwe) => `cwe-${cwe}`)]
      .join(" ")
      .toLowerCase(),
  };
}

function renderMasthead({ report, meta }: { report: Report; meta: ReportMeta }): string {
  const scanner = report.version ? `${report.tool} ${report.version}` : report.tool;
  const facts: [string, string | null][] = [
    ["Branch", meta.branch],
    ["Commit", meta.commit],
    ["Scanner", scanner],
    ["Query suite", meta.suite],
    ["Files scanned", report.filesScanned === null ? null : formatNumber(report.filesScanned)],
    ["Lines of code", report.linesOfCode === null ? null : formatNumber(report.linesOfCode)],
  ];
  const rows = facts
    .filter((fact): fact is [string, string] => fact[1] !== null)
    .map(([label, value]) => `<div class="fact"><dt>${escapeHtml(label)}</dt><dd>${escapeHtml(value)}</dd></div>`)
    .join("");

  return `<header class="masthead">
<div class="masthead-line">
<span class="wordmark">${escapeHtml(meta.project)}</span>
<time datetime="${meta.generatedAt.toISOString()}">${escapeHtml(formatDate(meta.generatedAt))}</time>
</div>
<h1>Security report</h1>
<dl class="facts">${rows}</dl>
</header>`;
}

function renderSummary(report: Report): string {
  const counts = countBySeverity(report.findings);
  const total = report.findings.length;
  const segments = SEVERITIES.filter((severity) => counts[severity] > 0)
    .map(
      (severity) =>
        `<span class="bar-segment sev-${severity}" style="flex-grow:${counts[severity]}" title="${SEVERITY_LABELS[severity]}: ${counts[severity]}"></span>`
    )
    .join("");
  const legend = SEVERITIES.map(
    (severity) => `<button class="legend-item sev-${severity}" type="button" data-filter="${severity}" aria-pressed="false"${
      counts[severity] === 0 ? " disabled" : ""
    }><span class="swatch"></span>${SEVERITY_LABELS[severity]}<span class="legend-count">${counts[severity]}</span></button>`
  ).join("");

  return `<section class="summary" aria-labelledby="summary-title">
<h2 id="summary-title" class="section-title">Summary</h2>
<p class="lead">${summarySentence({ total, counts })}</p>
${total > 0 ? `<div class="bar" role="img" aria-label="Findings by severity">${segments}</div>` : ""}
<div class="legend" role="group" aria-label="Filter by severity">${legend}</div>
<p class="note">Severity follows CodeQL's security-severity score from 0 to 10: critical from 9.0, high from 7.0, medium from 4.0. Each finding also lists the rule's own level (error, warning or note).</p>
</section>`;
}

function summarySentence({ total, counts }: { total: number; counts: Record<Severity, number> }): string {
  if (total === 0) return "No findings. CodeQL reported nothing for this scan.";

  const parts = SEVERITIES.filter((severity) => counts[severity] > 0).map(
    (severity) => `${counts[severity]} ${severity}`
  );

  return `<strong>${total} finding${total === 1 ? "" : "s"}</strong> — ${parts.join(", ")}.`;
}

function renderEmpty(): string {
  return `<section class="index" aria-label="Findings"><p class="empty">Nothing to fix in this scan.</p></section>`;
}

function renderIndex(numbered: NumberedFinding[]): string {
  const rows = numbered
    .map(
      ({ finding, number, anchor, searchText }) => `<tr data-finding data-severity="${finding.severity}" data-search="${escapeHtml(searchText)}">
<td class="col-number"><a href="#${anchor}">${number}</a></td>
<td class="col-severity">${renderSeverity(finding)}</td>
<td class="col-finding"><a href="#${anchor}">${escapeHtml(finding.title)}</a><code>${escapeHtml(
        formatLocation(finding.location)
      )}</code></td>
</tr>`
    )
    .join("");

  return `<section class="index" aria-labelledby="index-title">
<div class="index-head">
<h2 id="index-title" class="section-title">Findings</h2>
<label class="search"><span class="visually-hidden">Filter findings</span><input id="search" type="search" placeholder="Filter by file, rule or CWE" autocomplete="off"></label>
</div>
<p class="filter-state" id="filter-state" aria-live="polite"></p>
<table>
<thead><tr><th scope="col" class="col-number">No.</th><th scope="col" class="col-severity">Severity</th><th scope="col">Finding and location</th></tr></thead>
<tbody>${rows}</tbody>
</table>
<p class="empty" id="no-match" hidden>No findings match this filter.</p>
</section>`;
}

function renderSeverity(finding: Finding): string {
  const score = finding.score === null ? "" : `<span class="score">${finding.score.toFixed(1)}</span>`;
  return `<span class="severity sev-${finding.severity}"><span class="swatch"></span>${SEVERITY_LABELS[finding.severity]}${score}</span>`;
}

function renderDetails({
  numbered,
  readSource,
  isPrint,
}: {
  numbered: NumberedFinding[];
  readSource: SourceReader;
  isPrint: boolean;
}): string {
  return `<section class="details" aria-label="Finding details">
${numbered.map((entry) => renderFinding({ entry, readSource, isPrint })).join("")}
</section>`;
}

function renderFinding({
  entry,
  readSource,
  isPrint,
}: {
  entry: NumberedFinding;
  readSource: SourceReader;
  isPrint: boolean;
}): string {
  const { finding, number, anchor, searchText } = entry;

  return `<article class="finding" id="${anchor}" data-finding data-severity="${finding.severity}" data-search="${escapeHtml(searchText)}">
<header class="finding-head">
<a class="finding-number" href="#${anchor}">${number}</a>
<div class="finding-title">
<h3>${escapeHtml(finding.title)}</h3>
<p class="finding-meta">${renderSeverity(finding)}<span class="level">${escapeHtml(finding.level)}</span><code>${escapeHtml(
    formatLocation(finding.location)
  )}</code></p>
</div>
</header>
<div class="finding-body">
<p class="message">${renderMessage(finding.message)}</p>
${renderSnippet({ location: finding.location, readSource, context: SNIPPET_CONTEXT_LINES })}
${renderFlow({ finding, readSource, isPrint })}
${renderRule(finding)}
</div>
</article>`;
}

function renderMessage(parts: MessagePart[]): string {
  return parts
    .map((part) => {
      if (!part.reference) return escapeHtml(part.text);

      return `<em>${escapeHtml(part.text)}</em> <code class="ref">(${escapeHtml(formatLocation(part.reference))})</code>`;
    })
    .join("");
}

function renderRule(finding: Finding): string {
  const cwes = finding.cwes
    .map(
      (cwe) =>
        `<a href="https://cwe.mitre.org/data/definitions/${cwe}.html" target="_blank" rel="noreferrer">CWE-${cwe}</a>`
    )
    .join(", ");
  const facts = [
    `<code>${escapeHtml(finding.ruleId)}</code>`,
    cwes,
    finding.precision ? `precision ${escapeHtml(finding.precision)}` : "",
  ].filter((fact) => fact.length > 0);

  return `<p class="rule">${finding.description ? `${escapeHtml(finding.description)} ` : ""}<span class="rule-facts">${facts.join(
    " · "
  )}</span></p>`;
}

function renderFlow({
  finding,
  readSource,
  isPrint,
}: {
  finding: Finding;
  readSource: SourceReader;
  isPrint: boolean;
}): string {
  if (finding.flow.length < 2) return "";

  const steps = finding.flow
    .map(
      (step, index) => `<li>
<p class="step-head"><span class="step-role">${flowRole({ index, total: finding.flow.length })}</span><code>${escapeHtml(
        formatLocation(step)
      )}</code></p>
${renderSnippet({ location: step, readSource, context: 0 })}
</li>`
    )
    .join("");
  const extra =
    finding.extraPaths > 0 ? `, ${finding.extraPaths} more path${finding.extraPaths === 1 ? "" : "s"} not shown` : "";

  return `<details class="flow"${isPrint ? " open" : ""}>
<summary>Data flow <span class="flow-count">${finding.flow.length} steps${extra}</span></summary>
<ol>${steps}</ol>
</details>`;
}

function flowRole({ index, total }: { index: number; total: number }): string {
  if (index === 0) return "Source";
  if (index === total - 1) return "Sink";
  return `Step ${index + 1}`;
}

function renderSnippet({
  location,
  readSource,
  context,
}: {
  location: CodeLocation;
  readSource: SourceReader;
  context: number;
}): string {
  const lines = readSource(location.file);

  if (!lines) return `<p class="no-source">Source not available for <code>${escapeHtml(location.file)}</code>.</p>`;

  const { region } = location;
  const first = Math.max(region.startLine - context, 1);
  const last = Math.min((region.endLine ?? region.startLine) + context, lines.length);
  const rows = lines
    .slice(first - 1, last)
    .map((text, offset) => renderSourceLine({ text, lineNumber: first + offset, region }))
    .join("");

  return `<pre class="code"><code>${rows}</code></pre>`;
}

function renderSourceLine({ text, lineNumber, region }: { text: string; lineNumber: number; region: Region }): string {
  const firstLine = region.startLine;
  const lastLine = region.endLine ?? firstLine;
  const gutter = `<span class="ln">${lineNumber}</span>`;

  if (lineNumber < firstLine || lineNumber > lastLine) {
    return `<span class="line">${gutter}${escapeHtml(text)}</span>`;
  }

  const from = lineNumber === firstLine ? (region.startColumn ?? 1) - 1 : 0;
  const to = lineNumber === lastLine && region.endColumn !== undefined ? region.endColumn - 1 : text.length;

  return `<span class="line is-marked">${gutter}${escapeHtml(text.slice(0, from))}<mark>${escapeHtml(
    text.slice(from, to)
  )}</mark>${escapeHtml(text.slice(to))}</span>`;
}

function createSourceReader(sourceRoot: string): SourceReader {
  const root = resolve(sourceRoot);
  const cache = new Map<string, string[] | null>();

  return function readSource(file: string): string[] | null {
    const cached = cache.get(file);

    if (cached !== undefined) return cached;

    const lines = readLines({ root, file });
    cache.set(file, lines);

    return lines;
  };
}

function readLines({ root, file }: { root: string; file: string }): string[] | null {
  const path = resolve(root, file);

  if (!path.startsWith(`${root}${sep}`)) return null;

  try {
    return readFileSync(path, "utf8").split(/\r?\n/);
  } catch (error: unknown) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") return null;
    throw new Error(`Could not read ${file} for the report`, { cause: error });
  }
}

function countBySeverity(findings: Finding[]): Record<Severity, number> {
  return Object.fromEntries(
    SEVERITIES.map((severity) => [severity, findings.filter((finding) => finding.severity === severity).length])
  ) as Record<Severity, number>;
}

function formatLocation(location: CodeLocation): string {
  const { startLine, startColumn } = location.region;
  return startColumn === undefined ? `${location.file}:${startLine}` : `${location.file}:${startLine}:${startColumn}`;
}

function displayPath({ root, path }: { root: string; path: string }): string {
  const fromRoot = relative(root, path);
  return fromRoot.startsWith("..") ? path : fromRoot;
}

function formatDate(date: Date): string {
  return date.toLocaleString("en-GB", { day: "numeric", month: "long", year: "numeric", hour: "2-digit", minute: "2-digit" });
}

function formatNumber(value: number): string {
  return value.toLocaleString("en-US");
}

function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, (character) => HTML_ESCAPES[character] ?? character);
}

