const CLIENT_SCRIPT = `
(function () {
  var severity = "all";
  var legend = Array.prototype.slice.call(document.querySelectorAll("[data-filter]"));
  var rows = Array.prototype.slice.call(document.querySelectorAll("tbody [data-finding]"));
  var items = Array.prototype.slice.call(document.querySelectorAll("[data-finding]"));
  var search = document.getElementById("search");
  var state = document.getElementById("filter-state");
  var empty = document.getElementById("no-match");

  function matches(item, query) {
    return (severity === "all" || item.dataset.severity === severity) &&
      (query === "" || item.dataset.search.indexOf(query) !== -1);
  }

  function apply() {
    var query = search ? search.value.trim().toLowerCase() : "";
    items.forEach(function (item) { item.hidden = !matches(item, query); });
    var visible = rows.filter(function (row) { return !row.hidden; }).length;
    legend.forEach(function (item) {
      item.setAttribute("aria-pressed", String(item.dataset.filter === severity));
    });
    if (state) {
      state.textContent = visible === rows.length
        ? rows.length + " findings, most severe first"
        : "Showing " + visible + " of " + rows.length + " findings";
    }
    if (empty) empty.hidden = visible !== 0;
  }

  legend.forEach(function (item) {
    item.addEventListener("click", function () {
      severity = severity === item.dataset.filter ? "all" : item.dataset.filter;
      apply();
    });
  });
  if (search) search.addEventListener("input", apply);
  window.addEventListener("beforeprint", function () {
    items.forEach(function (item) { item.hidden = false; });
    document.querySelectorAll("details").forEach(function (details) { details.open = true; });
  });
  window.addEventListener("afterprint", apply);
  apply();
})();
`;
