const CLIENT_SCRIPT = `
(function () {
  var severity = "all";
  var cards = Array.prototype.slice.call(document.querySelectorAll("[data-filter]"));
  var findings = Array.prototype.slice.call(document.querySelectorAll(".finding"));
  var search = document.getElementById("search");
  var state = document.getElementById("filter-state");
  var empty = document.getElementById("no-match");

  function apply() {
    var query = search ? search.value.trim().toLowerCase() : "";
    var visible = 0;
    findings.forEach(function (finding) {
      var matches = (severity === "all" || finding.dataset.severity === severity) &&
        (query === "" || finding.dataset.search.indexOf(query) !== -1);
      finding.hidden = !matches;
      if (matches) visible += 1;
    });
    cards.forEach(function (card) {
      card.setAttribute("aria-pressed", String(card.dataset.filter === severity));
    });
    if (state) {
      var label = severity === "all" ? "all" : severity;
      state.textContent = "Showing " + visible + " of " + findings.length + " findings (" + label + ")";
    }
    if (empty && findings.length > 0) empty.hidden = visible !== 0;
  }

  cards.forEach(function (card) {
    card.addEventListener("click", function () {
      severity = severity === card.dataset.filter ? "all" : card.dataset.filter;
      apply();
    });
  });
  if (search) search.addEventListener("input", apply);
  window.addEventListener("beforeprint", function () {
    document.querySelectorAll("details").forEach(function (details) { details.open = true; });
  });
  apply();
})();
`;
